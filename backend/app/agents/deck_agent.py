def extract_section_for_product(raw_text, product_title):
    """Extracts bullet points for ONE product from a multi-product markdown section."""
    if not raw_text or not product_title:
        return []
    blocks = raw_text.split("---")
    for block in blocks:
        if product_title.lower() in block.lower():
            lines = block.splitlines()
            clean = []
            for line in lines:
                line = line.strip()
                if line.startswith("-"):
                    clean.append(line.replace("- ", "").strip())
            return clean
    return []

