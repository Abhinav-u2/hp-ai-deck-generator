# ----------------------
# MAIN GENERATOR (Final Version)
# ----------------------
def create_professional_ppt(
    sales_pitch=None,
    products=None,
    customer_query=None,
    output_file=None
):
    # Debug Prints
    print("\n=== DEBUG: SALES PITCH ===")
    print(json.dumps(sales_pitch, indent=4) if sales_pitch else "None")

    print("\n=== DEBUG: PRODUCTS ===")
    for p in products or []:
        print(json.dumps(p, indent=4))

    print("\n=== DEBUG: QUERY ===")
    print(customer_query)

    # Normalize Inputs
    pdf_title = sales_pitch.get("pitch_summary", "HP Proposal") if sales_pitch else "HP Proposal"
    extracted_requirements = sales_pitch.get("extracted_requirements", [])
    upsell_products = sales_pitch.get("upsell_opportunities", [])
    conclusion_text = sales_pitch.get("conclusion", "Recommended next steps")
    products = products or []
    output_file = output_file or "HP_Proposal.pptx"
    customer_query = customer_query or ""

    # Build PPT
    prs = Presentation()

    slide_title(prs, pdf_title)
    slide_requirements(prs, customer_query, extracted_requirements)

    # Individual Product Slides
    for prod in products[:5]:
        slide_product(prs, prod)

    
    def extract_specs(product):
        """
        Extracts all spec_* fields and returns a clean dict:
        {
            "Processor": "Intel i5",
            "Ram": "16GB",
            ...
        }
        """
        specs = {}

        for key, value in product.items():
            if key.startswith("spec_") and value not in (None, "", []):
                clean_key = key.replace("spec_", "").replace("_", " ").title()
                specs[clean_key] = value

        return specs

    
    
    # ----------------------
    # Build Specs Dictionary from spec_* keys
    # ----------------------
    specs_list = []

    for p in products:
        p["specs"] = extract_specs(p)
        specs_list.append(p["specs"])


    slide_comparison(prs, products,specs_list)
    slide_upsell(prs, upsell_products)
    slide_conclusion(prs, conclusion_text)

    prs.save(output_file)
    print(f"\n🎉 SUCCESS: PowerPoint generated → {output_file}")
    return output_file

