    PRODUCTS_PER_COLUMN = 3
    slide_num = 1

    for start in range(0, len(upsell_structured), 3):
        remaining = len(upsell_structured) - start
        cols_this_slide = 3 if remaining >= 3 else remaining

        col_width = usable_width / cols_this_slide
        total_cols_width = col_width * cols_this_slide
        left_offset = (SLIDE_WIDTH_IN - total_cols_width) / 2.0

        slide = prs.slides.add_slide(prs.slide_layouts[6])
