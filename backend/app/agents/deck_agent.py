def add_product_image_safe(slide, image_bytes, left, top, box_width, box_height):
    """Safely fit image inside bounding box without overflow."""
    
    # Place initially
    pic = slide.shapes.add_picture(image_bytes, left, top)

    # Original aspect ratio
    img_ratio = pic.width / pic.height
    box_ratio = box_width / box_height

    # Scale inside box
    if img_ratio > box_ratio:
        # Fit to width
        pic.width = box_width
        pic.height = int(box_width / img_ratio)
    else:
        # Fit to height
        pic.height = box_height
        pic.width = int(box_height * img_ratio)

    # Center inside bounding box
    pic.left = left + int((box_width - pic.width) / 2)
    pic.top  = top  + int((box_height - pic.height) / 2)



