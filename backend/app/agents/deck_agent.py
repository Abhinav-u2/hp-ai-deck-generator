def set_font(p, size, bold=False, color=TEXT_COLOR):
    """Applies font settings safely to paragraph runs."""
    for run in p.runs:
        run.font.name = FONT_NAME
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color

def add_footer(slide, text):
    """Adds a standard footer in bottom-left."""
    box = slide.shapes.add_textbox(Inches(0.6), Inches(7.0),
                                   Inches(9), Inches(0.4))
    tf = box.text_frame
    p = tf.paragraphs[0]
    p.text = text
    p.alignment = PP_ALIGN.LEFT
    set_font(p, 9, color=FOOTER_COLOR)

def apply_soft_gradient_background(slide):
    """
    Light violet/blue gradient like your screenshots
    (used on intro / requirements / comparison / upsell / conclusion).
    """
    fill = slide.background.fill
    fill.gradient()
    stops = fill.gradient_stops
    # ensure at least 2 stops exist
    while len(stops) < 2:
        stops.add()
    stops[0].position = 0
    stops[0].color.rgb = RGBColor(245, 248, 255)   # very light blue
    stops[1].position = 1
    stops[1].color.rgb = RGBColor(236, 234, 252)   # very light violet
    fill.gradient_angle = 45


