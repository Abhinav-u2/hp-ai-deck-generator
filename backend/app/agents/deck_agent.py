def slide_product(prs, product):
    """
    Product slide:
    - Left 1/3 = image + description
    - Right 2/3 = specs table
    """
    slide = prs.slides.add_slide(prs.slide_layouts[6])

    # -------------------------
    # Title
    # -------------------------
    title = product.get("model") or product.get("product_name") or "Unnamed Product"
    tbox = slide.shapes.add_textbox(Inches(0.6), Inches(0.5), Inches(9), Inches(0.7)).text_frame
    tbox.text = title
    set_font(tbox.paragraphs[0], 22, bold=True, color=BRAND_PRIMARY)

    # Left column: 1/3 width
    LEFT_X = Inches(0.6)
    LEFT_W = Inches(3.0)

    # -------------------------
    # IMAGE AREA (top-left)
    # -------------------------
    img_y = Inches(1.3)
    img_h = Inches(3.0)

    img_path = product.get("image_path")
    if img_path and os.path.exists(img_path):
        slide.shapes.add_picture(img_path, LEFT_X, Inches(1.4), width=LEFT_W, height=Inches(3.4))
    else:
        ph = slide.shapes.add_textbox(LEFT_X, img_y, LEFT_W, img_h)
        ph.text_frame.text = "Image not available"
        set_font(ph.text_frame.paragraphs[0], 12, bold=True)

    # -------------------------
    # DESCRIPTION (below image)
    # -------------------------
    desc = product.get("description", "")
    desc_y = Inches(1.3) + img_h + Inches(0.3)
    desc_h = Inches(2.5)  # controlled box height

    desc_box = slide.shapes.add_textbox(LEFT_X, desc_y, LEFT_W, desc_h)
    tf = desc_box.text_frame
    tf.word_wrap = True

    if desc:
        # Split into lines safely
        lines = desc.split("\n")

        # Ensure max 10 lines
        if len(lines) > 10:
            lines = lines[:9] + [lines[9][:50] + " ..."]

        # Write description line-by-line
        tf.text = "Description:"
        set_font(tf.paragraphs[0], 14, bold=True, color=BRAND_SECONDARY)

        for line in lines:
            p = tf.add_paragraph()
            p.text = line.strip()
            p.level = 1
            set_font(p, 12)

    else:
        tf.text = "Description not available"
        set_font(tf.paragraphs[0], 12, bold=True)

    # -------------------------
    # SPECIFICATIONS (right 2/3)
    # -------------------------
    specs = {}
    for key, val in product.items():
        if key.startswith("spec_") and val not in (None, "", []):
            clean = key.replace("spec_", "").replace("_", " ").title()
            specs[clean] = val

    if specs:
        table_x = Inches(4.0)     # 2/3 area starts here
        table_y = Inches(1.3)
        table_w = Inches(5.4)
        table_h = Inches(5.5)

        rows = len(specs) + 1
        table = slide.shapes.add_table(rows, 2, table_x, table_y, table_w, table_h).table

        # Headers
        table.cell(0, 0).text = "Specification"
        table.cell(0, 1).text = "Details"
        set_font(table.cell(0, 0).text_frame.paragraphs[0], 12, bold=True)
        set_font(table.cell(0, 1).text_frame.paragraphs[0], 12, bold=True)

        # Data
        for i, (k, v) in enumerate(specs.items(), start=1):
            table.cell(i, 0).text = k
            table.cell(i, 1).text = str(v)
            set_font(table.cell(i, 0).text_frame.paragraphs[0], 10)
            set_font(table.cell(i, 1).text_frame.paragraphs[0], 10)

    add_footer(slide, f"{title} — Product Details")
    return slide



