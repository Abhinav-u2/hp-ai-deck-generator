from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
import os
import json

# ----------------------
# BRAND COLORS / FONTS
# ----------------------
BRAND_PRIMARY = RGBColor(0, 66, 121)
BRAND_SECONDARY = RGBColor(0, 132, 180)
TEXT_COLOR = RGBColor(34, 34, 34)
FOOTER_COLOR = RGBColor(120, 120, 120)
FONT_NAME = 'Calibri'


# ----------------------
# Utilities
# ----------------------
def set_font(p, size, bold=False, color=TEXT_COLOR):
    """Applies font settings safely to paragraph runs."""
    for run in p.runs:
        run.font.name = FONT_NAME
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color


def add_footer(slide, text):
    """Adds a standard footer."""
    box = slide.shapes.add_textbox(Inches(0.6), Inches(7.0), Inches(9), Inches(0.4))
    p = box.text_frame.paragraphs[0]
    p.text = text
    p.alignment = PP_ALIGN.LEFT
    set_font(p, 9, color=FOOTER_COLOR)


# ----------------------
# Slide 1 — Title
# ----------------------


def slide_title(prs, pdf_title):
    # Blank slide
    slide = prs.slides.add_slide(prs.slide_layouts[6])

    # Create a text box centered horizontally
    left = Inches(1)
    top = Inches(2)
    width = Inches(8)     # wide enough to wrap naturally
    height = Inches(2)    # tall enough for 2–3 lines

    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.clear()  # remove auto-placeholder paragraph

    # Add paragraph
    p = tf.paragraphs[0]
    p.text = pdf_title
    p.alignment = PP_ALIGN.CENTER

    # Set font
    font = p.font
    font.bold = True
    font.size = Pt(34)
    font.color.rgb = BRAND_PRIMARY

    # Let PowerPoint wrap text automatically
    tf.word_wrap = True

    # AUTO-SHRINK (Important)
    # ensures long titles shrink instead of overflowing
    tf.auto_size = True

    add_footer(slide, "Generated by HP AI Sales Assistant")
    return slide



# ----------------------
# Slide 2 — User Query + Requirements
# ----------------------
def slide_requirements(prs, query, extracted_req):
    slide = prs.slides.add_slide(prs.slide_layouts[6])

    # Title
    header = slide.shapes.add_textbox(Inches(0.6), Inches(0.5), Inches(9), Inches(0.7)).text_frame
    header.text = "Customer Requirements"
    set_font(header.paragraphs[0], 22, bold=True, color=BRAND_PRIMARY)

    # User Query
    qbox = slide.shapes.add_textbox(Inches(0.6), Inches(1.3), Inches(8.5), Inches(1.2)).text_frame
    qbox.text = "User Query:"
    set_font(qbox.paragraphs[0], 16, bold=True)

    p = qbox.add_paragraph()
    p.text = query
    set_font(p, 14)

    # Requirements Section
    rbox = slide.shapes.add_textbox(Inches(0.6), Inches(2.8), Inches(8.5), Inches(4.8)).text_frame
    rbox.text = "Extracted Requirements:"
    set_font(rbox.paragraphs[0], 16, bold=True, color=BRAND_SECONDARY)

    for req in extracted_req:
        p = rbox.add_paragraph()
        p.text = f"• {req}"
        set_font(p, 14)

    add_footer(slide, "Customer Requirement Analysis")
    return slide


