    for i, prod in enumerate(products):
        name = prod.get("model") or prod.get("product_name") or f"Product {i+1}"
        table.cell(0, i + 1).text = name[:28]   # ✅ truncate header safely

    # -----------------------------
    # BODY ROWS (STRICT TEXT LIMIT)
    # -----------------------------
    row_bg_1 = RGBColor(230, 235, 245)
    row_bg_2 = RGBColor(245, 247, 252)

    for r, key in enumerate(all_keys, start=1):
        bg = row_bg_1 if r % 2 else row_bg_2

        # Feature name
        cell = table.cell(r, 0)
        cell.text = key[:20]
        cell.fill.solid()
