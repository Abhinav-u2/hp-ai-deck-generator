def slide_comparison(prs, products, specs_list):
    """
    Compare all products using pre-extracted specs_list.
    specs_list = [ {spec: value}, {spec: value}, ... ]
    """
    slide = prs.slides.add_slide(prs.slide_layouts[6])

    # Header
    header = slide.shapes.add_textbox(Inches(0.3), Inches(0.5), Inches(9), Inches(0.7)).text_frame
    header.text = "Product Comparison"
    set_font(header.paragraphs[0], 22, bold=True, color=BRAND_PRIMARY)

    # --------------------------------------------
    # Collect all unique spec keys across products
    # --------------------------------------------
    all_keys = set()
    for specs in specs_list:
        all_keys.update([k for k, v in specs.items() if v not in (None, "", [])])

    all_keys = sorted(all_keys)

    rows = len(all_keys) + 1
    cols = len(products) + 1

    # Table
    table = slide.shapes.add_table(
        rows, cols, Inches(0.3), Inches(1.3), Inches(9.4), Inches(5.4)
    ).table

    # --------------------------------------------
    # Header Row
    # --------------------------------------------
    table.cell(0, 0).text = "Feature"
    set_font(table.cell(0, 0).text_frame.paragraphs[0], 11, bold=True)

    for i, prod in enumerate(products):
        name = prod.get("model") or prod.get("product_name") or f"Product {i+1}"
        table.cell(0, i + 1).text = name
        set_font(table.cell(0, i + 1).text_frame.paragraphs[0], 11, bold=True)

    # --------------------------------------------
    # Body Rows
    # --------------------------------------------
    for r, key in enumerate(all_keys, start=1):
        table.cell(r, 0).text = key
        set_font(table.cell(r, 0).text_frame.paragraphs[0], 10, bold=True)

        for c, specs in enumerate(specs_list, start=1):
            val = specs.get(key, "N/A")
            table.cell(r, c).text = str(val)
            set_font(table.cell(r, c).text_frame.paragraphs[0], 9)

    add_footer(slide, "Comparison Across Recommended Products")
    return slide




