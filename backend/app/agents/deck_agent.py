# MAIN GENERATOR
# ===============================================================
def create_professional_ppt(
    sales_pitch=None,
    products=None,
    customer_query=None,
    output_file=None
):
    print("\n=== DEBUG: SALES PITCH ===")
    print(json.dumps(sales_pitch, indent=4) if sales_pitch else "None")

    print("\n=== DEBUG: PRODUCTS ===")
    for p in products or []:
        print(json.dumps(p, indent=4))

    print("\n=== DEBUG: QUERY ===")
    print(customer_query)

    # Normalize Inputs
    pdf_title = sales_pitch.get("pitch_summary", "HP Proposal") if sales_pitch else "HP Proposal"
    extracted_requirements = sales_pitch.get("extracted_requirements", {})
    upsell_products = sales_pitch.get("upsell_opportunities", {})
    conclusion_text = sales_pitch.get("conclusion", "Recommended next steps")
    products = products or []
    output_file = output_file or "HP_Proposal.pptx"
    customer_query = customer_query or ""

    prs = Presentation()

    # Slide order matching your screenshots:
    # 0: static cover
    # 1: intro text
    # 2: customer requirements
    slide_static_cover(prs)          # screenshot 1
    slide_intro(prs, pdf_title)      # screenshot 2
    slide_requirements(prs, customer_query, extracted_requirements)  # screenshot 3

    # Product slides (screenshots 4, 4, 4, ...)
    for prod in products[:5]:
        slide_product(prs, prod, sales_pitch)

    # Build specs dicts from spec_* keys
    def extract_specs(product):
        specs = {}
        for key, value in product.items():
            if key.startswith("spec_") and value:
                clean_key = key.replace("spec_", "").replace("_", " ").title()

                text = str(value).replace("\n", " ").strip()
                text = text[:160]   # ✅ hard safety clamp

                specs[clean_key] = text
        return specs


    specs_list = []
    for p in products:
        p["specs"] = extract_specs(p)
        specs_list.append(p["specs"])

    # Comparison slide (screenshot 5)
    slide_comparison(prs, products, specs_list)

    # Upsell slides (screenshots 6 & 7)
    structured_upsell = upsell_products.get("structured", [])
    build_upsell_slides(prs, structured_upsell)

    # Conclusion (screenshot 8)
    slide_conclusion(prs, conclusion_text)

    prs.save(output_file)
    print("\n🎉 SUCCESS: PowerPoint generated →", output_file)
    return output_file
