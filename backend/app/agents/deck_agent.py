    # PREPARE DATA (LIMIT ROWS)
    # -----------------------------
    all_keys = []
    for specs in specs_list:
        for k in specs:
            if k not in all_keys:
                all_keys.append(k)

    MAX_ROWS = 9     # ✅ CRITICAL: prevents overflow
    all_keys = all_keys[:MAX_ROWS]

    rows = len(all_keys) + 1
    cols = len(products) + 1

    table = slide.shapes.add_table(
        rows, cols, table_left, table_top, table_width, table_height
    ).table

    # -----------------------------
    # COLUMN WIDTHS (STATIC SAFE)
    # -----------------------------
    table.columns[0].width = Inches(1.6)

    col_width = int((table_width - Inches(1.6)) / (cols - 1))

    for c in range(1, cols):
        table.columns[c].width = col_width


    # -----------------------------
    # HEADER ROW
    # -----------------------------
    header_bg = RGBColor(80, 130, 190)
    header_text = RGBColor(255, 255, 255)

    for c in range(cols):
        cell = table.cell(0, c)
        cell.fill.solid()
        cell.fill.fore_color.rgb = header_bg
        tf = cell.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
